HARNESS_BY_ID: dict[str, HarnessDescriptor] = {h.id: h for h in HARNESS_CATALOG}


def evaluate_pair(source_id: str, target_id: str) -> dict[str, Any]:
    """Deterministically compute per-object transfer fidelity for any `(source, target)` pair."""
    src = HARNESS_BY_ID.get(source_id)
    dst = HARNESS_BY_ID.get(target_id)
    if src is None:
        raise ValueError(f"unknown source harness: {source_id}")
    if dst is None:
        raise ValueError(f"unknown target harness: {target_id}")

    if not src.read_supported:
        status = "source_unsupported_requires_export"
    elif not dst.write_supported:
        status = "portable_archive_and_handoff_only"
    else:
        status = "native_projection_plus_lossless_sidecar"

    def dim(src_has: bool, dst_has: bool, sidecar_fallback: str) -> str:
        if not src_has:
            return "not_applicable_in_source"
        if dst.write_supported and dst_has:
            return "native_preserved"
        return sidecar_fallback

    return {
        "source": src.id,
        "target": dst.id,
        "overall_mode": status,
        "evidence_levels": {"source": src.evidence_level, "target": dst.evidence_level},
        "object_fidelity": {
            "projects_workspaces": dim(src.native_projects, dst.native_projects, "preserved_in_portable_hierarchy_and_handoff"),
            "section_groups": dim(src.native_sections, dst.native_sections, "preserved_in_portable_hierarchy_no_target_section_api"),
            "linear_messages_and_followups": "native_preserved" if (src.read_supported and dst.write_supported) else "archived_in_portable_json",
            "branches_and_forks": "native_tree_dag" if (src.native_branch_dag and dst.native_branch_dag and dst.write_supported) else "split_per_leaf_session_plus_exact_dag_in_portable_json",
            "subtasks_and_master_child_links": "preserved_in_metadata_and_portable_relations",
            "tool_calls_and_results": dim(src.native_tool_events, dst.native_tool_events, "preserved_in_portable_sidecar"),
            "attachments_and_images": "copied_with_sha256_in_bundle_assets; native_inline_depends_on_target_lane" if src.native_attachments else "not_applicable_in_source",
            "links_and_usage_tokens": "extracted_in_canonical_graph_and_handoff_report",
            "skills": "native_copy_projected" if (src.native_skills and dst.native_skills) else "staged_in_bundle_resources",
            "mcp_servers": "sanitized_template_without_secrets" if (src.native_mcp and dst.native_mcp) else "staged_in_bundle_resources",
            "credentials_and_permissions": "never_auto_migrated_for_security",
            "schedules": "staged_disabled_until_user_enables",
        },
        "api_key_gateway_compatible_target": dst.api_key_gateway_compatible,
    }


